"""
Програма має:

1. Запитати кількість замовлених страв.
2. Запитати ціну кожної страви.
3. Запитати відсоток чайових (наприклад, 10%, 15% або 20%).
4. Розрахувати:
   - загальну вартість страв;
   - суму чайових;
   - загальну суму (вартість страв + чайові).
5. Якщо загальна вартість страв перевищує $2000,
   застосувати знижку 10% ДО розрахунку чайових.
"""

# TODO: реалізуйте задачу 1 тут
count = int(input("Введіть кількість замовлених страв: "))
total = 0 
for j in range(count):
    price = float(input(f"Введіть ціну страви {j+1}: "))
    total += price
percent = float(input("Введіть відсоток чайових 10 або 20 або 15: "))
if total > 2000:
    total *= 0.9
    print("сума більше $2000 - - знижка 10%  ")
chayovi = total * (percent / 100)
final_suma = total + chayovi
print(f"загальна вартість страв: {round(total, 2)}")
print(f"сума чайових: {round(chayovi, 2)}")
print(f"загальна сума: {round(final_suma, 2)}")
