"""
Користувач вводить температуру у градусах Фаренгейта
для кожного дня тижня (7 днів).

Програма має:

1. Перетворити кожну температуру у градуси Цельсія.
2. Після кожного введення показати повідомлення:

   - "Холодно" — нижче 10°C
   - "Тепло" — від 10°C до 28°C
   - "Спекотно" — вище 28°C
   - "Дуже спекотно" — вище 36°C

3. Наприкінці вивести:
   - середню температуру за тиждень;
   - мінімальну температуру;
   - максимальну температуру.
"""

# TODO: реалізуйте задачу 2 тут
spic = ["понеділок", "вівторок", "середа", "четвер", "п'ятниця", "субота", "неділя"]
m = [float(input(f"Введіть температуру у градусах Фаренгейта для {i}: ")) for i in spic]
def far(f):
    return (f - 32) * 5/9
cel = [] 
for i, j in enumerate(m):
    c = far(j)
    cel.append(c)
    
    if c < 10:
        print(f"{spic[i]}: Холодно ({round(c,2)})")
    elif 10 <= c <= 28:
        print(f"{spic[i]}: Тепло ({round(c, 2)})")
    elif 28 < c <= 36:
        print(f"{spic[i]}: Спекотно ({round(c,2)})")
    else:
        print(f"{spic[i]}: Дуже спекотно ({round(c, 2)})")
avg = sum(cel) / 7
mi = min(cel)
ma = max(cel)
print(f"середня температура:{round(avg, 2)}")
print(f"мінімальна: {round(mi,2)}")
print(f"максимальна:{round(ma, 2)}")

